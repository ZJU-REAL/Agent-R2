"""real_dataset.py -- RL dataset for the real recipe.

Loads the pre-built train.parquet (generated by data_sythesis pipeline)
and formats it for verl's multi-turn rollout.

Each row in the parquet has:
  - prompt: list of chat messages (system + user)
  - data_source: str
  - extra_info: dict with input_dir, question, rubric, sample_dir, task_id
"""
from __future__ import annotations

import os
from typing import Any

import pandas as pd
from torch.utils.data import Dataset

from verl.utils.model import compute_position_id_with_mask


class RealRLDataset(Dataset):
    """Dataset for real-world productivity task RL training.

    Each sample contains:
      - input_ids: tokenized prompt (not used directly, raw_prompt is used)
      - raw_prompt: list of chat messages for multi-turn rollout
      - extra_info: passed through to reward function and tool create()

    The dataset returns raw_prompt so that the ToolAgentLoop can apply
    the chat template with tools correctly.
    """

    def __init__(self, parquet_files: str | list[str], tokenizer, config):
        """
        Args:
            parquet_files: path or list of paths to parquet files
            tokenizer: HuggingFace tokenizer
            config: verl data config (OmegaConf)
        """
        if isinstance(parquet_files, str):
            parquet_files = [parquet_files]

        dfs = [pd.read_parquet(f) for f in parquet_files]
        self.df = pd.concat(dfs, ignore_index=True)
        self.tokenizer = tokenizer
        self.config = config

        self.max_prompt_length = getattr(config, "max_prompt_length", 2048)

        print(f"[RealRLDataset] Loaded {len(self.df)} samples from {parquet_files}")

    def __len__(self):
        return len(self.df)

    def __getitem__(self, idx: int) -> dict[str, Any]:
        row = self.df.iloc[idx]

        # raw_prompt: list of chat message dicts (system + user)
        raw_prompt = row["prompt"]
        if hasattr(raw_prompt, "tolist"):
            raw_prompt = raw_prompt.tolist()
        # Ensure it's a plain list of dicts
        raw_prompt = [dict(m) for m in raw_prompt]

        extra_info = row.get("extra_info", {})
        if hasattr(extra_info, "item"):
            extra_info = extra_info.item()
        extra_info = dict(extra_info) if extra_info is not None else {}

        # Convert numpy arrays in extra_info to lists
        extra_info = _normalize_extra_info(extra_info)

        data_source = row.get("data_source", "real")

        return {
            "raw_prompt": raw_prompt,
            "data_source": data_source,
            "extra_info": extra_info,
        }


def _normalize_extra_info(info: Any) -> Any:
    """Recursively convert numpy arrays / numpy scalars to Python native types."""
    import numpy as np

    if isinstance(info, dict):
        return {k: _normalize_extra_info(v) for k, v in info.items()}
    elif isinstance(info, (list, tuple)):
        return [_normalize_extra_info(v) for v in info]
    elif isinstance(info, np.ndarray):
        return _normalize_extra_info(info.tolist())
    elif isinstance(info, (np.integer,)):
        return int(info)
    elif isinstance(info, (np.floating,)):
        return float(info)
    else:
        return info
