"""preprocess.py -- Preprocess the data_sythesis output parquet for RL training.

This script takes the train.parquet generated by the data_sythesis pipeline
and adds the necessary fields for verl multi-turn RL training:
  - tools_kwargs: per-tool create/release kwargs (including input_dir for sandbox uploads)

The output is saved as a new parquet file ready for verl training.

Usage (from the verl root; these are also the defaults):
    python recipe/agent_r2/preprocess.py \
        --input ../Agent-R2/data_sythesis/output/train.parquet \
        --output recipe/agent_r2/data/train.parquet
"""
from __future__ import annotations

import argparse
import os
from pathlib import Path

import numpy as np
import pandas as pd

try:
    from recipe.agent_r2._settings import load_settings
except ImportError:  # run as a plain script: python recipe/agent_r2/preprocess.py
    from _settings import load_settings


def _normalize_extra_info(info):
    """Recursively convert numpy arrays / scalars to Python native types."""
    if isinstance(info, dict):
        return {k: _normalize_extra_info(v) for k, v in info.items()}
    elif isinstance(info, (list, tuple)):
        return [_normalize_extra_info(v) for v in info]
    elif isinstance(info, np.ndarray):
        return _normalize_extra_info(info.tolist())
    elif isinstance(info, np.integer):
        return int(info)
    elif isinstance(info, np.floating):
        return float(info)
    else:
        return info


def build_tools_kwargs(extra_info: dict) -> dict:
    """Build tools_kwargs for a single sample.

    The terminal tool needs:
      - create_kwargs.input_dir: path to the input attachments directory
        so that the sandbox tool can upload them before the rollout starts

    Args:
        extra_info: normalized extra_info dict from parquet

    Returns:
        tools_kwargs dict keyed by tool name
    """
    input_dir = extra_info.get("input_dir", "")
    if isinstance(input_dir, str):
        for old, new in load_settings().get("path_rewrites") or []:
            input_dir = input_dir.replace(old, new)
    return {
        "terminal": {
            "create_kwargs": {
                "input_dir": input_dir,
            },
        }
    }


def preprocess(input_path: str, output_path: str):
    """Preprocess the parquet file for RL training."""
    print(f"Loading {input_path}...")
    df = pd.read_parquet(input_path)
    print(f"  Loaded {len(df)} rows, columns: {df.columns.tolist()}")

    # Process each row
    rows = []
    for idx, row in df.iterrows():
        extra_info = row.get("extra_info", {})
        if hasattr(extra_info, "item"):
            extra_info = extra_info.item()
        extra_info = _normalize_extra_info(extra_info) if extra_info is not None else {}

        # Add tools_kwargs
        extra_info["tools_kwargs"] = build_tools_kwargs(extra_info)

        # Normalize prompt
        raw_prompt = row["prompt"]
        if hasattr(raw_prompt, "tolist"):
            raw_prompt = raw_prompt.tolist()
        raw_prompt = [dict(m) for m in raw_prompt]

        rows.append({
            "prompt": raw_prompt,
            "data_source": row.get("data_source", "real"),
            "extra_info": extra_info,
            "reward_model": {"style": "rule", "ground_truth": ""},  # required by NaiveRewardManager
        })

    out_df = pd.DataFrame(rows)

    # Save
    out_path = Path(output_path)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_df.to_parquet(output_path, index=False)
    print(f"Saved {len(out_df)} rows to {output_path}")

    # Verify
    verify = pd.read_parquet(output_path)
    sample_extra = verify.iloc[0]["extra_info"]
    print(f"  Verification: extra_info keys = {list(sample_extra.keys())}")
    print(f"  tools_kwargs = {sample_extra.get('tools_kwargs', {})}")


if __name__ == "__main__":
    recipe_dir = Path(__file__).resolve().parent
    agent_dir = recipe_dir.parents[2] / "Agent-R2"
    parser = argparse.ArgumentParser(description="Preprocess train.parquet for RL training")
    parser.add_argument(
        "--input",
        default=str(agent_dir / "data_sythesis" / "output" / "train.parquet"),
        help="Input parquet path",
    )
    parser.add_argument(
        "--output",
        default=str(recipe_dir / "data" / "train.parquet"),
        help="Output parquet path",
    )
    args = parser.parse_args()
    preprocess(args.input, args.output)
